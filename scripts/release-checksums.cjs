const { createHash } = require('node:crypto')
const { readdirSync, readFileSync, writeFileSync } = require('node:fs')
const { resolve, join } = require('node:path')
const root = resolve(__dirname, '../apps/desktop/release/installers')
const files = readdirSync(root).filter(name => /\.(exe|dmg|zip|AppImage|deb)$/.test(name)).sort()
if (!files.length) throw new Error('No release installers found')
const lines = files.map(name => `${createHash('sha256').update(readFileSync(join(root, name))).digest('hex')}  ${name}`)
writeFileSync(join(root, 'SHA256SUMS.txt'), lines.join('\n') + '\n')
console.log(lines.join('\n'))
